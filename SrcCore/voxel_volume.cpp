void voxel_volume::to_free(voxel_offset v)
{
	assert(v < m_cells.size());
	*reinterpret_cast<voxel_offset*>(&m_cells[v]) = m_free;
	m_free = v;
}

voxel_offset voxel_volume::from_free()
{
	let v = m_free;

	if (v != voxel_offset::empty_) {
		m_free = *reinterpret_cast<voxel_offset*>(&m_cells[v]);
	}

	return v;
}


double voxel_volume::update(const Vec3& bc, double br, Vec3& uvw)
{
	//transform into the parallelepiped coordinate system
	ball3d<double> b;
	b.c = (bc - m_origin) / m_voxel_size;
	b.r = br / m_voxel_size;//must be sqrt(3)/2

	let r2=b.r*b.r;
	let r21=(b.r+1)*(b.r+1);

	//points taken into account (an integer parallelepiped that completely contains the ball)

	double	xd1=b.c[0] -b.r,	xd2=b.c[0] +b.r+1,
			yd1=b.c[1] -b.r,	yd2=b.c[1] +b.r+1,
			zd1=b.c[2] -b.r,	zd2=b.c[2] +b.r+1;

	let sz = m_octree.get_side();

	if (xd1 < 1 || yd1 < 1 || zd1 < 1 || 
		xd2 >= sz - 1 || yd2 >= sz - 1 || zd2 >= sz - 1) 
	{
		assert(false);
		return 0;
	};


	unsigned	x1=unsigned(xd1),	x2=unsigned(xd2),
				y1=unsigned(yd1),	y2=unsigned(yd2),
				z1=unsigned(zd1),	z2=unsigned(zd2);

	

	double ret=0;
	constexpr double rm = 1.0 / static_cast<int>(voxel::bit_shift);


	for (unsigned z=z1;z<=z2;++z){
		for (unsigned y=y1;y<=y2;++y){
			for (unsigned x=x1;x<=x2;++x){

				auto offset = m_octree.get_cell_offset({ x, y, z });

				//maybe the point is already completely inside?
				if (voxel_offset::inside == offset)continue;

				ray3d<double> l;

				l.p << x, y, z;

				let d2 = (l.p - b.c).squaredNorm();

				if (d2 < r2) {//inside the ball
					m_octree.create_cell({ x, y, z }, true);
					if (voxel_offset::empty_ != offset) {
						to_free(offset);
					}
					continue;
				}


				if (voxel_offset::empty_ == offset) {//the vertex first entered the ball

					auto& idx = m_octree.create_cell({ x, y, z }, false);
					
					//creating and filling a cell
					idx = from_free();

					if (idx== voxel_offset::empty_) {
						m_cells.emplace_back();
						if (m_use_colors) {
							m_data.emplace_back();
						}
						idx = voxel_offset(m_cells.size() - 1);//update the index after inserting data
					}

					m_cells[idx].clear();
					if (m_use_colors) {
						m_data[idx].clear();
					}
					
					offset = idx;
					
				}
				assert(octree::is_reg(offset));

				auto* v = &m_cells[offset];
			

				if (m_use_colors) {
					double d = 1 - (b.c - Vec3(x, y, z)).squaredNorm() / r21;
					if (d < 0)d = 0;
					m_data[offset].update(uvw[0], uvw[1], uvw[2], d);
				}
	
				if (d2>=r21)continue;//too far - the ball has no effect

				double t1,t2;

				unsigned nv;

			
				l.d<<1,0,0;
				if (b.intersect(l,&t1,&t2)){//intersected by X
					if (t1>=0 && t1<1){
						nv=voxel::get(t1);//double-checking
						if (nv<v->x1){
							ret=std::max(ret,(v->x1-nv)*rm);
							v->x1=nv;
						}
					}else if (t2<=0 && t2>-1){
						nv = voxel::get(-t2);
						if (nv < v->x2) {
							ret = std::max(ret, (v->x2 - nv)*rm);
							v->x2 = nv;
						}
					}
				}
				l.d<<0,1,0;
				if (b.intersect(l,&t1,&t2)){//intersected by Y
					if (t1>=0 && t1<1){
						nv = voxel::get(t1);
						if (nv < v->y1) {
							ret = std::max(ret, (v->y1 - nv)*rm);
							v->y1 = nv;
						}

					}else if (t2<=0 && t2>-1){
						nv = voxel::get(-t2);
						if (nv < v->y2) {
							ret = std::max(ret, (v->y2 - nv)*rm);
							v->y2 = nv;
						}
					}
				}
				l.d<<0,0,1;
				if (b.intersect(l,&t1,&t2)){//intersected by Z
					if (t1>=0 && t1<1){
						nv = voxel::get(t1);
						if (nv < v->z1) {
							ret = std::max(ret, (v->z1 - nv)*rm);
							v->z1 = nv;
						}
					}else if (t2<=0 && t2>-1){
						nv = voxel::get(-t2);
						if (nv < v->z2) {
							ret = std::max(ret, (v->z2 - nv)*rm);
							v->z2 = nv;
						}
					}
				}

			}
		}
	}

	return ret;
}

void voxel_volume::triangulate(mesh& m) const
{
	//let's delete anything that was there before
	m.clear();

	let sz = m_octree.get_side();

	point3u p0, p1;
	m_octree.get_bound(p0, p1);

	

	//expand by 1 voxel to the left
	if (p0.x > 0)p0.x--;
	if (p0.y > 0)p0.y--;
	if (p0.z > 0)p0.z--;

	//need some space on the right
	if (p1.x + 2 > sz)p1.x = sz - 2;
	if (p1.y + 2 > sz)p1.y = sz - 2;
	if (p1.z + 2 > sz)p1.z = sz - 2;

	constexpr unsigned  ofarr[8] = {0,1,3,2,4,5,7,6,};

	let wa = 1.0/((p1.z - p0.z + 1)*(p1.y - p0.y + 1));

	auto* rt = ims_worker::get();

	for (unsigned z = p0.z; z <= p1.z; ++z) {
		for (unsigned y = p0.y; y <= p1.y; ++y) {


			if (rt->is_need_stop2()) {
				m.clear();
				return;
			}
			rt->work_add(wa);

			for (unsigned x = p0.x; x <= p1.x; ++x) {
				point3d p[12];//vertices - lie on the edges of the cube
				int ci = 0;

				voxel v[8];
				bool vins[8];

				for (unsigned i = 0; i < 8; ++i) {
					let q = ofarr[i];

					let offset = m_octree.get_cell_offset(point3u(
						x + ((q >> 0) & 1),
						y + ((q >> 1) & 1),
						z + ((q >> 2) & 1)
					));

					if (offset==voxel_offset::empty_) {
						v[i].clear();
						vins[i] = false;
					} else if (offset == voxel_offset::inside) {
						vins[i] = true;
						ci |= (1 << i);
					}else{
						v[i] = m_cells[offset];
						vins[i] = false;
					}
					
				}

		
				const uint16_t e=EdgeTable[ci];

	

				//maybe there are no polygons in the cube?
				if (e == 0)continue;


				if (e & 1){//0-1 (x-x)
					p[0].set(x,y,z);	p[0].x+=vins[0]?v[1].xm():v[0].xp();
				}
				if (e & 2){//1-2 (y-y)
					p[1].set(x+1,y,z);	p[1].y+=vins[1]?v[2].ym():v[1].yp();
				}
				if (e & 4){//3-2 (x-x)
					p[2].set(x,y+1,z);	p[2].x+=vins[3]?v[2].xm():v[3].xp();
				}
				if (e & 8){//0-3 (y-y)
					p[3].set(x,y,z);	p[3].y+=vins[0]?v[3].ym():v[0].yp();
				}
				if (e & 16){//4-5 (x-x)
					p[4].set(x,y,z+1);	p[4].x+=vins[4]?v[5].xm():v[4].xp();
				}
				if (e & 32){//5-6 (y-y)
					p[5].set(x+1,y,z+1);p[5].y+=vins[5]?v[6].ym():v[5].yp();
				}
				if (e & 64){//7-6 (x-x)
					p[6].set(x,y+1,z+1);p[6].x+=vins[7]?v[6].xm():v[7].xp();
				}
				if (e & 128){//4-7 (y-y)
					p[7].set(x, y, z+1);p[7].y+=vins[4]?v[7].ym():v[4].yp();
				}
				if (e & 256){//0-4 (z-z)
					p[8].set(x,y,z);	p[8].z+=vins[0]?v[4].zm():v[0].zp();
				}
				if (e & 512){//1-5 (z-z)
					p[9].set(x+1,y,z);	p[9].z+=vins[1]?v[5].zm():v[1].zp();
				}
				if (e & 1024){//2-6 (z-z)
					p[10].set(x+1,y+1,z);p[10].z+=vins[2]?v[6].zm():v[2].zp();
				}
				if (e & 2048){//3-7 (z-z)
					p[11].set(x,y+1,z);p[11].z+=vins[3]?v[7].zm():v[3].zp();
				}

				////////////////////////////////////////////////////////////////

				point3d d[12];//vertex colors


				if (m_use_colors) {
					point3d s[8];


					for (unsigned i = 0; i < 8; ++i) {
						let q = ofarr[i];

						let offset = m_octree.get_cell_offset(point3u(
							x + ((q >> 0) & 1),
							y + ((q >> 1) & 1),
							z + ((q >> 2) & 1)
						));

						if (octree::is_reg(offset)) {
							s[i] = m_data[offset].get_color();
						} else {
							s[i] = point3d(1, 1, 1);
						}

					}

					//double q;

					if (e & 1) {//0-1 (x-x)
						d[0] = vins[0] ? s[1] : s[0];
						//q = vins[0] ? v[1].xm() : v[0].xp();
						//d[0] = s[0] * (1 - q) + s[1] * q;
					}
					if (e & 2) {//1-2 (y-y)
						d[1] = vins[1] ? s[2] : s[1];
						//q = vins[1] ? v[2].ym() : v[1].yp();
						//d[1] = s[1] * (1 - q) + s[2] * q;
					}
					if (e & 4) {//3-2 (x-x)
						d[2] = vins[3] ? s[2] : s[3];
						//q = vins[3] ? v[2].xm() : v[3].xp();
						//d[2] = s[3] * (1 - q) + s[2] * q;
					}
					if (e & 8) {//0-3 (y-y)
						d[3] = vins[0] ? s[3] : s[0];
						//q = vins[0] ? v[3].ym() : v[0].yp();
						//d[3] = s[0] * (1 - q) + s[3] * q;
					}
					if (e & 16) {//4-5 (x-x)
						d[4] = vins[4] ? s[5] : s[4];
						//q = vins[4] ? v[5].xm() : v[4].xp();
						//d[4] = s[4] * (1 - q) + s[5] * q;
					}
					if (e & 32) {//5-6 (y-y)
						d[5] = vins[5] ? s[6] : s[5];
						//q = vins[5] ? v[6].ym() : v[5].yp();
						//d[5] = s[5] * (1 - q) + s[6] * q;
					}
					if (e & 64) {//7-6 (x-x)
						d[6] = vins[7] ? s[6] : s[7];
						//q = vins[7] ? v[6].xm() : v[7].xp();
						//d[6] = s[7] * (1 - q) + s[6] * q;
					}
					if (e & 128) {//4-7 (y-y)
						d[7] = vins[4] ? s[7] : s[4];
						//q = vins[4] ? v[7].ym() : v[4].yp();
						//d[7] = s[4] * (1 - q) + s[7] * q;
					}
					if (e & 256) {//0-4 (z-z)
						d[8] = vins[0] ? s[4] : s[0];
						//q = vins[0] ? v[4].zm() : v[0].zp();
						//d[8] = s[0] * (1 - q) + s[4] * q;
					}
					if (e & 512) {//1-5 (z-z)
						d[9] = vins[1] ? s[5] : s[1];
						//q = vins[1] ? v[5].zm() : v[1].zp();
						//d[9] = s[1] * (1 - q) + s[5] * q;
					}
					if (e & 1024) {//2-6 (z-z)
						d[10] = vins[2] ? s[6] : s[2];
						//q = vins[2] ? v[6].zm() : v[2].zp();
						//d[10] = s[2] * (1 - q) + s[6] * q;
					}
					if (e & 2048) {//3-7 (z-z)
						d[11] = vins[3] ? s[7] : s[3];
						//q = vins[3] ? v[7].zm() : v[3].zp();
						//d[11] = s[3] * (1 - q) + s[7] * q;
					}
				}
				
				
				for (unsigned i = 0; TriTable[ci][i] != -1; i += 3){
					auto nv=static_cast<mesh_idx_t>(m.m_ver.size());
					m.m_tr.emplace_back(mesh_triangle(nv+2,nv+1,nv));//order is important

					int idx1=TriTable[ci][i];
					int idx2=TriTable[ci][i+1];
					int idx3=TriTable[ci][i+2];

					m.m_ver.emplace_back(point3f(p[idx1].data()));
					m.m_ver.emplace_back(point3f(p[idx2].data()));
					m.m_ver.emplace_back(point3f(p[idx3].data()));

					if (m_use_colors) {
						m.m_uvw.emplace_back(d[idx1].data());
						m.m_uvw.emplace_back(d[idx2].data());
						m.m_uvw.emplace_back(d[idx3].data());
					}
				}
			}
			

		}
	}

}





double voxel_volume::get_radius() const
{
	//tested, less is impossible - holes appear
	return m_voxel_size*(sqrt(3.0)/2*1.01);
};



void voxel_volume::revert_to_space( mesh& m ) const
{
	
	for (auto& v : m.m_ver) {
		v.p.x = float(v.p.x*m_voxel_size + m_origin[0]);
		v.p.y = float(v.p.y*m_voxel_size + m_origin[1]);
		v.p.z = float(v.p.z*m_voxel_size + m_origin[2]);
	}
}


void voxel_volume::init(const box<double>& bx, size_t resolution, bool use_colors)
{
	let dim = bx.get_dim();
	
	assert(dim >= 1 && dim <= 3);

	//increase the bounding parallelepiped by 10 percent
	let sz = bx.max_size();
	let offset = sz*0.1;

	//expand in all directions
	for (size_t i = 0; i < 3; ++i) {
		m_origin(i)= (i < dim ? bx.c[0](i) : 0) - offset;
	}
	m_voxel_size = (sz + 2 * offset) / resolution;


	clear();
	m_octree.set_depth(log_val(resolution));

	m_use_colors = use_colors;
}



void voxel_volume::clear()
{
	m_octree.clear();
	m_cells.clear();
	m_data.clear();
	m_free=voxel_offset::empty_;
}

void voxel_volume::clear_mem()
{
	clear();
	m_octree.clear_mem();
	m_cells.shrink_to_fit();
	m_data.shrink_to_fit();
}



