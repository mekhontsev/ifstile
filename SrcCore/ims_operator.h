//within the AST, immediately after var_header, there are two blocks
//left side of the assignment
//right side (variable definition)
struct var_header
{
	using type = var_header_type;

	//has a different meaning at the block loading stage
	//the low-order bit means subs
	type ref8; //index in m_refs
	type next; //offset of the next variable

	static constexpr type pack(size_t ref, bool is_subs) 
	{
		if (ref_is_builtin(ref)) {
			return (type)ref;
		}
		return type((ref << 1) | (is_subs ? 1 : 0));
	}

	static constexpr size_t unpack_ref(type ref)
	{
		return ref >> 1;
	}

	static constexpr bool unpack_subs(type ref)
	{
		return (ref & 1) != 0;
	}

	size_t get_ref() const 
	{
		return unpack_ref(ref8);
	}

	bool is_subs() const
	{
		return unpack_subs(ref8);
	}

	bool is_builtin() const
	{
		return ref_is_builtin(ref8);
	}

	bool is_builtin(builtin_ids bid) const
	{
		return ref_is_builtin(ref8, bid);
	}

	//next == nil : there is no next var
	static constexpr type nil = std::numeric_limits<type>::max();

	static constexpr type offset_left = 1;
	static constexpr type offset_right = 2;
	//how many elements does the variable declaration take?
	//var_header + left expression + right expression
	static constexpr type total_elems = 3;
};

